[ORG 0X7E00]

RUNOS:
xor ax, ax

JMP LOG_SYS
LABELS:
SHUTDOWN:
HALT
JMP SHUTDOWN


LOADTEXT:
MOV BX, 0
MOV BYTE[CURRTEXTWRITTEN], LOAD_PLACEHOLDER
DOTHEDIRTYWORK:
MOV AL, LOAD_PLACEHOLDER[BX]
CMP AL, '\'
JE NONNORM
JNE NORM
NORM:
MOV AH, 0X0E
INT 0X10
INC BX
CMP BX, WORD[PLACEHOLDER_LEN]
JB DOTHEDIRTYWORK
JA HOPON
NONNORM:
INC BX
JMP SPECIAL_NEWLINE
CHECKBX:
CMP BX, WORD[PLACEHOLDER_LEN]
JB DOTHEDIRTYWORK
JA HOPON

TEXTEDITOR:
MOV BYTE[OP], 0
MOV BYTE[OP+1],0
MOV WORD[CURRIND],0
MOV BYTE[CURRTEXT],0
MOV BYTE[LEN], 17
MOV BYTE[CURRTEXT], 'P'
MOV BYTE[CURRTEXT+1], 'L'
MOV BYTE[CURRTEXT+2], 'E'
MOV BYTE[CURRTEXT+3], 'A'
MOV BYTE[CURRTEXT+4], 'S'
MOV BYTE[CURRTEXT+5], 'E'
MOV BYTE[CURRTEXT+6], ' '
MOV BYTE[CURRTEXT+7], 'S'
MOV BYTE[CURRTEXT+8], 'E'
MOV BYTE[CURRTEXT+9], 'L'
MOV BYTE[CURRTEXT+10], 'E'
MOV BYTE[CURRTEXT+11], 'C'
MOV BYTE[CURRTEXT+12], 'T'
MOV BYTE[CURRTEXT+13], ' '
MOV BYTE[CURRTEXT+14], 'F'
MOV BYTE[CURRTEXT+15], 'I'
MOV BYTE[CURRTEXT+16], 'L'
MOV BYTE[CURRTEXT+17], 'E'
;SKIP FILE CHOSE LOGIC COMPLETELY TEMPORARILY TO FOCUS ON THE TEXT EDITOR FULLY
MOV EBX,0
HOPON:
MOV AH, 0X00
INT 0X16
MOV AH, 0X0E
INT 0X10
CMP AL, 0DH
JNE ORDENARY
JE ONENTER
ORDENARY:
CMP EBX, 0
JE ON1
JNE ONELSE
ON1:
MOV BYTE[CURRTEXTWRITTEN], AL
INC EBX
JMP HOPON
ONELSE:
MOV BYTE[CURRTEXTWRITTEN+EBX], AL
INC EBX
JMP HOPON
ONENTER:
CMP EBX, 0
JE ON11
JNE ONELSE1
ON11:
MOV BYTE[CURRTEXTWRITTEN], "\"
INC EBX
JMP NEWLINE_SPEC
ONELSE1:
MOV BYTE[CURRTEXTWRITTEN+EBX], "\"
INC EBX
JMP NEWLINE_SPEC

SPECLOG:
MOV BX, 0
ACTSL:
MOV AH, 0X0E
MOV AL, CURRTEXT[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]
JBE ACTSL
JAE NEWLINE_SPEC

NEWLINE_SPEC:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
MOV DH, BYTE[CURRENTROW]
MOV DL, 0
MOV BH ,0
INT 0X10
CMP DH, 24
JAE RESET
JB HOPON
RESET:
MOV AH, 0X02
MOV DL, 0
MOV BH ,0
MOV DH, BYTE[CURRENTROW]
INT 0X10
JMP HOPON

SPECIAL_NEWLINE:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
MOV DH, BYTE[CURRENTROW]
MOV DL, 0
MOV BH ,0
INT 0X10
JMP CHECKBX

LOG:
MOV BX,0
MOV BYTE[OP],0
MOV BYTE[OP+1], 0
ACTLOG:
MOV AH, 0X0E
MOV AL, CURRTEXT[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]

JBE ACTLOG
JAE NEWLINE_USER

LOG_SYS:
MOV BX, 0
ACTLOGSYS:
MOV AH, 0X0E
MOV AL, CURRTEXT[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]
JBE ACTLOGSYS
JAE NEWLINE

NEWLINE:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
MOV DH, BYTE[CURRENTROW]
MOV DL, 0
MOV BH ,0
INT 0X10

JMP TEXT_TYPING

NEWLINE_USER:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
MOV DH, BYTE[CURRENTROW]
MOV DL, 0
MOV BH ,0
INT 0X10
JMP TEXT_TYPING

TEXT_TYPING:
MOV AH, 0X00
INT 16H
MOV BYTE[CKP], AL
MOV AH, 0X0E
INT 0X10
MOV AL, BYTE[CKP]
CMP AL, 0DH
JE PROCESS
CMP BYTE[OP], 0
JE SETZERO
JNE NEXTOPER
SETZERO:
MOV BYTE[OP], AL
JMP TEXT_TYPING
NEXTOPER:
CMP BYTE[OP+1], 0
JE DOIT
JNE TEXT_TYPING
DOIT:
MOV BYTE[OP+1], AL
JMP TEXT_TYPING

PROCESS:
CMP BYTE[OP], 0X61
JE BA
JNE BB
BA:
;CMP COMMANDS FOR CHILDS OF BRANCH A   
;A
CMP BYTE[OP+1], 0X61
JE LOG
;B
CMP BYTE[OP+1], 0X62
JE SHUTDOWN
BB:
CMP BYTE[OP], 0X62
JE BB_C
JNE BC

BB_C:
;COMMAND CMPS FOR CHILDS OF B BRANCH

BC:

;BRANCH T
BT:
CMP BYTE[OP],'t'
JE BT_C
JNE BP_

BT_C:


;X
CMP BYTE[OP+1], 'x'
JE TEXTEDITOR

BP_:

JMP NEWLINE_USER
;VARIABLES
LOAD_PLACEHOLDER DB 'C','U','T','E','\','C','A','T','B','O','Y'
CURRTEXT DB "W","E","L","C","O","M","E"," ", "T","O"," ", "O", "S", "_","1"
PLACEHOLDER_LEN DW 11
CURRENTROW DB 8
ENTERP DB 0
CURRTEXTWRITTEN DB 0
CURRIND DW 0
LEN DW 14
OP DB 0,0
CURRTEXTLEN DB 0
EXTRA_C DB 0
CKP DB 0
