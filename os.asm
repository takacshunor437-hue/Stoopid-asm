TEXT_TYPING:
MOV AH, 0X00
INT 16H
MOV BYTE[CKP], AL
MOV AH, 0X0E
INT 0X10
MOV AL, BYTE[CKP]
CMP AL, 0DH
JE PROCESS
CMP BYTE[OP], 0
JE SETZERO
JNE NEXTOPER
SETZERO:
MOV BYTE[OP], AL
JMP TEXT_TYPING
NEXTOPER:
CMP BYTE[OP+1], 0
JE DOIT
JNE TEXT_TYPING
DOIT:
MOV BYTE[OP+1], AL
JMP TEXT_TYPING

PROCESS:
CMP BYTE[OP], 0X61
JE BA
JNE BB
BA:
;CMP COMMANDS FOR CHILDS OF BRANCH A   
;A
CMP BYTE[OP+1], 0X61
JE LOG
;B
CMP BYTE[OP+1], 0X62
JE SHUTDOWN
BB:
CMP BYTE[OP], 0X62
JE BB_C
JNE BC

BB_C:
;COMMAND CMPS FOR CHILDS OF B BRANCH

BC:

;BRANCH T
BT:
CMP BYTE[OP],'t'
JE BT_C
JNE BP_

BT_C:


;X
CMP BYTE[OP+1], 'x'
JE TEXTEDITOR

BP_:

MOV BYTE[OP],0
MOV BYTE[OP+1],0
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
INC DH
MOV DL, 0
MOV BH ,0
INT 0X10
JMP TEXT_TYPING
