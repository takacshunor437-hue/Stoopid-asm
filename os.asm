[ORG 0X7E00]

RUNOS:
xor ax, ax
MOV DH, 8
JMP LOG_SYS
LABELS:
SHUTDOWN:
HALT
JMP SHUTDOWN


LOADTEXT:
MOV BX, 0
MOV BYTE[CURRTEXTWRITTEN], LOAD_PLACEHOLDER
DOTHEDIRTYWORK:
MOV AL, LOAD_PLACEHOLDER[BX]
CMP AL, 0X5C 
JE NONNORM
JNE NORM
NORM:
MOV AH, 0X0E
INT 0X10
INC BX
CMP BX, WORD[PLACEHOLDER_LEN]
JB DOTHEDIRTYWORK
JA HOPON
NONNORM:
INC BX
JMP SPECIAL_NEWLINE
CHECKBX:
CMP BX, WORD[PLACEHOLDER_LEN]
JB DOTHEDIRTYWORK
JA HOPON

QUIT_TXT:
MOV BYTE[CURRTEXTWRITTEN + BX], 0
CMP BX, 0
JA DECREMENTBX
JE LOGTEXT
DECREMENTBX:
DEC BX
LOGTEXT:
MOV WORD[LEN], 19
MOV BYTE[CURRTEXT], 'Y'
MOV BYTE[CURRTEXT+1], 'O'
MOV BYTE[CURRTEXT+2], 'U'
MOV BYTE[CURRTEXT+3], ' '
MOV BYTE[CURRTEXT+4], 'E'
MOV BYTE[CURRTEXT+5], 'X'
MOV BYTE[CURRTEXT+6], 'I'
MOV BYTE[CURRTEXT+7], 'T'
MOV BYTE[CURRTEXT+8], ' '
MOV BYTE[CURRTEXT+9], 'T'
MOV BYTE[CURRTEXT+10], 'H'
MOV BYTE[CURRTEXT+11], 'E'
MOV BYTE[CURRTEXT+12], ' '
MOV BYTE[CURRTEXT+13], 'E'
MOV BYTE[CURRTEXT+14], 'D'
MOV BYTE[CURRTEXT+15], 'I'
MOV BYTE[CURRTEXT+16], 'T'
MOV BYTE[CURRTEXT+17], 'O'
MOV BYTE[CURRTEXT+18], 'R'
MOV BYTE[CURRTEXT+19], '.'

;LOG MESSAGE
MOV BX, 0
ACTSL111:
MOV AH, 0X0E
MOV AL, CURRTEXT[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]
JBE ACTSL111
JAE NEWLINE


TEXTEDITOR:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
ADD DH,1
MOV DL, 0
MOV BH ,0
INT 0X10
MOV BYTE[OP], 0
MOV BYTE[OP+1],0
MOV WORD[CURRIND],0
MOV BYTE[CURRTEXT],0
MOV BYTE[LEN], 19
MOV BYTE[CURRTEXT], 'W'
MOV BYTE[CURRTEXT+1], 'E'
MOV BYTE[CURRTEXT+2], 'L'
MOV BYTE[CURRTEXT+3], 'C'
MOV BYTE[CURRTEXT+4], 'O'
MOV BYTE[CURRTEXT+5], 'M'
MOV BYTE[CURRTEXT+6], 'E'
MOV BYTE[CURRTEXT+7], ' '
MOV BYTE[CURRTEXT+8], 'T'
MOV BYTE[CURRTEXT+9], 'O'
MOV BYTE[CURRTEXT+10], ' '
MOV BYTE[CURRTEXT+11], 'O'
MOV BYTE[CURRTEXT+12], 'S'
MOV BYTE[CURRTEXT+13], '_'
MOV BYTE[CURRTEXT+14], '1'
MOV BYTE[CURRTEXT+15], ' '
MOV BYTE[CURRTEXT+16], 'T'
MOV BYTE[CURRTEXT+17], 'E'
MOV BYTE[CURRTEXT+18], 'X'
MOV BYTE[CURRTEXT+19], 'T'
JMP SPECLOG

HOPON:
MOV BX, 0
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
ADD DH,1
MOV DL, 0
MOV BH ,0
INT 0X10
MOV BX, 0
ACTUALTXTL:
MOV AH, 0X00
INT 0X16
MOV AH, 0X0E
INT 0X10

;ADDITIONAL FUNCTIONS
;QUITTING:
CMP AL, 0X11
JE QUIT_TXT

CMP AL, 0DH
JE ONENTER_P
JNE REGULAR

REGULAR:
MOV BYTE[CURRTEXTWRITTEN + BX], AL
INC BX
JMP ACTUALTXTL
ONENTER_P:
MOV BYTE[CURRTEXTWRITTEN + BX], 0X5C
INC BX
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
ADD DH,1
XOR DL, DL 
MOV BH ,0
INT 0X10
JMP ACTUALTXTL

L:
MOV BX, 0
ACTSL1:
MOV AH, 0X0E
MOV AL, CURRTEXTWRITTEN[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]
JBE ACTSL1
JAE ACTUALTXTL

SPECLOG:
MOV BX, 0
ACTSL:
MOV AH, 0X0E
MOV AL, CURRTEXT[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]
JBE ACTSL
JAE HOPON

SPECIAL_NEWLINE:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
MOV DH, BYTE[CURRENTROW]
MOV DL, 0
MOV BH ,0
INT 0X10
JMP CHECKBX


LOG:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
INC DH
MOV DL, 0
MOV BH ,0
INT 0X10
MOV BX,0
MOV BYTE[OP],0
MOV BYTE[OP+1], 0
ACTLOG:
MOV AH, 0X0E
MOV AL, CURRTEXT[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]
JBE ACTLOG
JAE NEWLINE_USER

LOG_SYS:
MOV BX, 0
ACTLOGSYS:
MOV AH, 0X0E
MOV AL, CURRTEXT[BX]
INT 0X10
ADD BX,1
CMP BX, WORD[LEN]
JBE ACTLOGSYS
JAE NEWLINE

NEWLINE:
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
INC DH
MOV DL, 0
MOV BH ,0
INT 0X10
JMP TEXT_TYPING

NEWLINE_USER:
MOV BYTE[OP],0
MOV BYTE[OP+1],0
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
INC DH
MOV DL, 0
MOV BH ,0
INT 0X10
JMP TEXT_TYPING

TEXT_TYPING:
MOV AH, 0X00
INT 16H
MOV BYTE[CKP], AL
MOV AH, 0X0E
INT 0X10
MOV AL, BYTE[CKP]
CMP AL, 0DH
JE PROCESS
CMP BYTE[OP], 0
JE SETZERO
JNE NEXTOPER
SETZERO:
MOV BYTE[OP], AL
JMP TEXT_TYPING
NEXTOPER:
CMP BYTE[OP+1], 0
JE DOIT
JNE TEXT_TYPING
DOIT:
MOV BYTE[OP+1], AL
JMP TEXT_TYPING

PROCESS:
CMP BYTE[OP], 0X61
JE BA
JNE BB
BA:
;CMP COMMANDS FOR CHILDS OF BRANCH A   
;A
CMP BYTE[OP+1], 0X61
JE LOG
;B
CMP BYTE[OP+1], 0X62
JE SHUTDOWN
BB:
CMP BYTE[OP], 0X62
JE BB_C
JNE BC

BB_C:
;COMMAND CMPS FOR CHILDS OF B BRANCH

BC:

;BRANCH T
BT:
CMP BYTE[OP],'t'
JE BT_C
JNE BP_

BT_C:


;X
CMP BYTE[OP+1], 'x'
JE TEXTEDITOR

BP_:

MOV BYTE[OP],0
MOV BYTE[OP+1],0
MOV AH, 0X02
ADD BYTE[CURRENTROW], 1
INC DH
MOV DL, 0
MOV BH ,0
INT 0X10
JMP TEXT_TYPING
;VARIABLES
LOAD_PLACEHOLDER DB 'C','U','T','E','\','C','A','T','B','O','Y'
CURRTEXT DB "W","E","L","C","O","M","E"," ", "T","O"," ", "O", "S", "_","1"
PLACEHOLDER_LEN DW 11
CURRENTROW DB 8
ENTERP DB 0
CURRTEXTWRITTEN DB 0
CURRIND DW 0
LEN DW 14
OP DB 0,0
CURRTEXTLEN DB 0
EXTRA_C DB 0
CKP DB 0
